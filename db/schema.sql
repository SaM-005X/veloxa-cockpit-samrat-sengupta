-- ============================================================================
-- Engineering & Operations Tables (Populated Day 3+)
-- ============================================================================

CREATE TABLE IF NOT EXISTS jira_versions (
    version_name TEXT PRIMARY KEY,
    release_target_date TEXT,
    previous_target_date TEXT,
    last_updated_by TEXT,
    last_updated_date TEXT,
    status TEXT,
    source_file TEXT NOT NULL,
    release_date TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS jira_issues (
    issue_key TEXT PRIMARY KEY,
    issue_type TEXT NOT NULL,
    epic_key TEXT,
    summary TEXT NOT NULL,
    status TEXT NOT NULL,
    assignee_id TEXT,
    story_points DOUBLE PRECISION,
    created_date TEXT,
    updated_date TEXT,
    source_file TEXT NOT NULL,
    release_date TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS git_commits (
    commit_hash TEXT PRIMARY KEY,
    author_name TEXT NOT NULL,
    author_email TEXT NOT NULL,
    canonical_entity_id TEXT,
    repo_name TEXT,
    committed_at_ist TEXT NOT NULL,
    event_date TEXT NOT NULL,
    is_late_night BOOLEAN NOT NULL DEFAULT FALSE,
    is_weekend BOOLEAN NOT NULL DEFAULT FALSE,
    message TEXT,
    source_file TEXT NOT NULL,
    release_date TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS incidents (
    incident_id TEXT PRIMARY KEY,
    severity TEXT NOT NULL,
    title TEXT NOT NULL,
    service TEXT,
    occurred_date TEXT NOT NULL,
    responder_ids TEXT,
    status TEXT,
    summary TEXT,
    source_file TEXT NOT NULL,
    release_date TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS oncall_rota (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    week_start TEXT NOT NULL,
    week_end TEXT NOT NULL,
    primary_entity_id TEXT NOT NULL,
    secondary_entity_id TEXT,
    source_file TEXT NOT NULL,
    release_date TEXT NOT NULL
);

-- ============================================================================
-- Cockpit Agent & Voice Note Governance Tables
-- ============================================================================

CREATE TABLE IF NOT EXISTS agent_profiles (
    employee_id TEXT PRIMARY KEY,
    visibility_scope TEXT NOT NULL,
    grounded_summary TEXT NOT NULL,
    assumed_personal_context TEXT NOT NULL,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (employee_id) REFERENCES employees(entity_id)
);

CREATE TABLE IF NOT EXISTS voice_note_decisions (
    note_id TEXT PRIMARY KEY,
    release_date TEXT NOT NULL,
    ceo_request TEXT NOT NULL,
    decision_type TEXT NOT NULL, -- 'implemented', 'partial_pushback', 'refused'
    response_summary TEXT NOT NULL,
    doc_path TEXT NOT NULL
);

-- ============================================================================
-- Temporal & Query Indexes
-- ============================================================================

CREATE INDEX IF NOT EXISTS idx_evidence_release ON evidence_index(release_date, event_date);
CREATE INDEX IF NOT EXISTS idx_conflicts_release ON conflicts(release_date);
CREATE INDEX IF NOT EXISTS idx_emails_release ON emails(release_date, event_date);
CREATE INDEX IF NOT EXISTS idx_docs_release ON documents(release_date, doc_type);
CREATE INDEX IF NOT EXISTS idx_gl_release ON gl_transactions(release_date, event_date, cost_center);
CREATE INDEX IF NOT EXISTS idx_payroll_sum_release ON payroll_summary(release_date, period_month);
CREATE INDEX IF NOT EXISTS idx_git_release ON git_commits(release_date, canonical_entity_id);
CREATE INDEX IF NOT EXISTS idx_jira_release ON jira_issues(release_date, assignee_id);
