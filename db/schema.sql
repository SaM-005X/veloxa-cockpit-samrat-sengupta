-- Veloxa CXO Cockpit — Relational Schema (PostgreSQL / Supabase Primary, SQLite Mirror)
-- Every operational and evidence table includes `release_date` (YYYY-MM-DD)
-- to enforce strict Point-in-Time isolation (`WHERE release_date <= :as_of_date`).

CREATE TABLE IF NOT EXISTS ingestion_runs (
    run_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    release_tag TEXT NOT NULL UNIQUE,
    release_date TEXT NOT NULL,
    source_dir TEXT,
    files_loaded INTEGER NOT NULL DEFAULT 0,
    records_loaded INTEGER NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'completed',
    loaded_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================================
-- Layer 2: Canonical Entities, Reporting Lines & Alias Resolution
-- ============================================================================

CREATE TABLE IF NOT EXISTS employees (
    entity_id TEXT PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT,
    department TEXT NOT NULL,
    title TEXT NOT NULL,
    manager_id TEXT,
    join_date TEXT,
    exit_date TEXT,
    location TEXT,
    employment_type TEXT NOT NULL DEFAULT 'FTE',
    status TEXT NOT NULL DEFAULT 'Active',
    is_agent_persona BOOLEAN NOT NULL DEFAULT FALSE,
    release_date TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS reporting_lines (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    employee_id TEXT NOT NULL,
    manager_id TEXT,
    department TEXT NOT NULL,
    effective_from TEXT NOT NULL,
    effective_to TEXT,
    source_ref TEXT,
    release_date TEXT NOT NULL,
    FOREIGN KEY (employee_id) REFERENCES employees(entity_id)
);

CREATE TABLE IF NOT EXISTS entity_aliases (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    alias_text TEXT NOT NULL,
    canonical_id TEXT NOT NULL,
    entity_type TEXT NOT NULL, -- 'person', 'contractor', 'vendor', 'tool', 'project'
    canonical_name TEXT NOT NULL,
    notes TEXT,
    release_date TEXT NOT NULL,
    UNIQUE(alias_text, canonical_id)
);

-- ============================================================================
-- Layer 2: Atomic Evidence Index & Explicit Conflict Registry
-- ============================================================================

CREATE TABLE IF NOT EXISTS evidence_index (
    evidence_id TEXT PRIMARY KEY,
    source_file TEXT NOT NULL,
    source_type TEXT NOT NULL, -- 'export', 'email', 'document', 'transcript', 'voice_note'
    location TEXT NOT NULL,    -- sheet/tab/row, page, timestamp, or email header
    fact_text TEXT NOT NULL,
    entities_json TEXT NOT NULL DEFAULT '[]',
    event_date TEXT,
    release_date TEXT NOT NULL,
    reliability TEXT NOT NULL DEFAULT 'Medium', -- 'High', 'Medium', 'Low'
    conflict_group_id TEXT
);

CREATE TABLE IF NOT EXISTS conflicts (
    conflict_id TEXT PRIMARY KEY,
    topic TEXT NOT NULL,
    claim_a_evidence_id TEXT,
    claim_b_evidence_id TEXT,
    summary TEXT NOT NULL,
    resolution_status TEXT NOT NULL DEFAULT 'open', -- 'open', 'resolved', 'disputed'
    verified_conclusion TEXT,
    release_date TEXT NOT NULL
);

-- ============================================================================
-- Unstructured & Semi-Structured Source Records (Emails & Documents)
-- ============================================================================

CREATE TABLE IF NOT EXISTS emails (
    email_id TEXT PRIMARY KEY,
    sender_raw TEXT NOT NULL,
    sender_entity_id TEXT,
    recipients_raw TEXT,
    cc_raw TEXT,
    subject TEXT NOT NULL,
    sent_at TEXT,
    event_date TEXT,
    body_text TEXT NOT NULL,
    source_file TEXT NOT NULL,
    release_date TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS documents (
    doc_id TEXT PRIMARY KEY,
    source_file TEXT NOT NULL,
    doc_type TEXT NOT NULL, -- 'brief', 'board_update', 'transcript', 'voice_note', 'pdf_report'
    title TEXT NOT NULL,
    section_label TEXT NOT NULL DEFAULT 'body',
    content_text TEXT NOT NULL,
    event_date TEXT,
    release_date TEXT NOT NULL
);

-- ============================================================================
-- Finance Domain Tables (Day 1: GL & Payroll)
-- ============================================================================

CREATE TABLE IF NOT EXISTS gl_transactions (
    voucher_id TEXT PRIMARY KEY,
    txn_date TEXT NOT NULL,
    event_date TEXT NOT NULL,
    account_code TEXT NOT NULL,
    account_name TEXT,
    cost_center TEXT,
    vendor_name TEXT,
    canonical_vendor TEXT,
    description TEXT,
    amount_inr DOUBLE PRECISION NOT NULL,
    entered_by TEXT,
    source_file TEXT NOT NULL,
    release_date TEXT NOT NULL
);

-- Aggregated safe-to-expose payroll table (complies with CFO rule in T2)
CREATE TABLE IF NOT EXISTS payroll_summary (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    period_month TEXT NOT NULL, -- YYYY-MM
    department TEXT NOT NULL,
    headcount INTEGER NOT NULL,
    total_gross_inr DOUBLE PRECISION NOT NULL,
    total_net_inr DOUBLE PRECISION,
    prepared_by TEXT,
    notes TEXT,
    source_file TEXT NOT NULL,
    release_date TEXT NOT NULL,
    UNIQUE(period_month, department, source_file)
);

-- Restricted individual payroll audit table: NEVER exposed to CEO Q&A directly.
-- Used strictly for internal anomaly detection (e.g., proration day counts).
CREATE TABLE IF NOT EXISTS payroll_restricted (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    period_month TEXT NOT NULL,
    employee_id TEXT NOT NULL,
    days_paid DOUBLE PRECISION,
    days_in_month INTEGER,
    gross_inr DOUBLE PRECISION,
    net_inr DOUBLE PRECISION,
    prepared_by TEXT,
    anomaly_flag TEXT,
    source_file TEXT NOT NULL,
    release_date TEXT NOT NULL,
    UNIQUE(period_month, employee_id, source_file)
);

-- ============================================================================
-- HR & People Operations Tables (Populated Day 2+)
