"""Dual-backend database manager for Veloxa CXO Cockpit.

Supports:
1. Local SQLite mirror (`veloxa.db`) — always initialized and kept in sync so
   fresh-clone evaluation works offline and without external credentials.
2. Supabase PostgreSQL (`DATABASE_URL`) — primary cloud store when configured.
"""

from __future__ import annotations

import os
import re
import sqlite3
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Iterator

from dotenv import load_dotenv

load_dotenv()

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SQLITE_PATH = REPO_ROOT / "veloxa.db"
SCHEMA_PATH = REPO_ROOT / "db" / "schema.sql"


def _to_sqlite_ddl(pg_sql: str) -> str:
    """Translate PostgreSQL DDL in db/schema.sql into valid SQLite DDL."""
    sql = pg_sql.replace("GENERATED BY DEFAULT AS IDENTITY", "AUTOINCREMENT")
    sql = sql.replace("DOUBLE PRECISION", "REAL")
    sql = re.sub(r"\bBOOLEAN\b", "INTEGER", sql)
    sql = sql.replace("DEFAULT FALSE", "DEFAULT 0")
    sql = sql.replace("DEFAULT TRUE", "DEFAULT 1")
    return sql


class DatabaseManager:
    """Manages SQLite mirror and optional Supabase PostgreSQL connection."""

    def __init__(
        self,
        sqlite_path: Path | str | None = None,
        database_url: str | None = None,
    ) -> None:
        self.sqlite_path = Path(sqlite_path) if sqlite_path else DEFAULT_SQLITE_PATH
        self.database_url = (
            database_url if database_url is not None else os.getenv("DATABASE_URL", "").strip()
        )

    @property
    def postgres_enabled(self) -> bool:
        return bool(self.database_url)

    @contextmanager
    def sqlite_conn(self) -> Iterator[sqlite3.Connection]:
        conn = sqlite3.connect(self.sqlite_path)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON;")
        try:
            yield conn
            conn.commit()
        finally:
            conn.close()

    @contextmanager
    def postgres_conn(self) -> Iterator[Any]:
        if not self.database_url:
            raise RuntimeError("DATABASE_URL is not configured.")
        import psycopg2
        from psycopg2.extras import RealDictCursor

        conn = psycopg2.connect(self.database_url, cursor_factory=RealDictCursor)
        try:
            yield conn
            conn.commit()
        finally:
            conn.close()

    def init_schema(self, sync_postgres: bool = True) -> dict[str, str]:
        """Apply db/schema.sql to local SQLite and (if configured) Supabase Postgres."""
        raw_schema = SCHEMA_PATH.read_text(encoding="utf-8")
        sqlite_ddl = _to_sqlite_ddl(raw_schema)

        self.sqlite_path.parent.mkdir(parents=True, exist_ok=True)
        with self.sqlite_conn() as conn:
            conn.executescript(sqlite_ddl)

        status = {"sqlite": f"initialized ({self.sqlite_path.name})"}

        if sync_postgres and self.postgres_enabled:
            with self.postgres_conn() as pg_conn:
                with pg_conn.cursor() as cur:
                    cur.execute(raw_schema)
            status["postgres"] = "initialized (Supabase PostgreSQL)"
        else:
            status["postgres"] = "skipped (DATABASE_URL not set; using SQLite mirror)"

        return status

    def query(
        self,
        sql: str,
        params: tuple[Any, ...] | list[Any] = (),
        prefer_postgres: bool = False,
    ) -> list[dict[str, Any]]:
        """Execute a read-only SELECT query and return list of dicts."""
        if prefer_postgres and self.postgres_enabled:
            pg_sql = sql.replace("?", "%s")
            with self.postgres_conn() as pg_conn:
                with pg_conn.cursor() as cur:
                    cur.execute(pg_sql, params)
                    return [dict(row) for row in cur.fetchall()]

        with self.sqlite_conn() as conn:
            rows = conn.execute(sql, params).fetchall()
            return [dict(row) for row in rows]

    def table_counts(self, use_postgres: bool = False) -> dict[str, int]:
        """Return row counts for core tables in local SQLite or Supabase Postgres."""
        tables = [
            "ingestion_runs",
            "employees",
            "reporting_lines",
            "entity_aliases",
            "evidence_index",
            "conflicts",
            "emails",
            "documents",
            "gl_transactions",
            "payroll_summary",
            "payroll_restricted",
        ]
        counts: dict[str, int] = {}
        if use_postgres and self.postgres_enabled:
            with self.postgres_conn() as pg_conn:
                with pg_conn.cursor() as cur:
                    for tbl in tables:
                        cur.execute(f"SELECT COUNT(*) AS cnt FROM {tbl}")
                        row = cur.fetchone()
                        counts[tbl] = int(row["cnt"]) if row else 0
            return counts

        with self.sqlite_conn() as conn:
            for tbl in tables:
                row = conn.execute(f"SELECT COUNT(*) AS cnt FROM {tbl}").fetchone()
                counts[tbl] = int(row["cnt"]) if row else 0
        return counts
